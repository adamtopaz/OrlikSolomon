#!/usr/bin/env bash
# Compile isolated fixtures and exercise the exact interface checker used by the default audit.
# Deliberate library-data references live outside OrlikSolomon/ and are never imported by it.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

lake build --wfail audit OrlikSolomon.Geometry.Hyperplane Verso.Doc

fixture_tmp="$(mktemp -d /tmp/issue-140-interface-audit.XXXXXX)"
trap 'rm -rf -- "$fixture_tmp"' EXIT

# Keep Lake's package and local build paths, adding the temporary compiled modules first.
fixture_lean_path="$(lake env printenv LEAN_PATH)"
fixture_audit="$(pwd)/.lake/build/bin/audit"
fixture_sources="scripts/tests/interface-audit"

negative_fixtures=(
  TypeLeak ValueLeak PredicateLeak ProofRegionLeak PrivateLeak AuxLeak BinderLeak GeneratedAuxLeak
  VersoLeak
)
positive_fixtures=(ProofOnly MathlibTransitive)
all_fixtures=("${negative_fixtures[@]}" "${positive_fixtures[@]}")

for fixture in "${all_fixtures[@]}"; do
  fixture_module="InterfaceAudit${fixture}"
  cp "$fixture_sources/$fixture_module.lean" "$fixture_tmp/"
  if ! lake env lean -DwarningAsError=true -DmaxSynthPendingDepth=3 -DautoImplicit=false \
      --root="$fixture_tmp" -o "$fixture_tmp/$fixture_module.olean" \
      "$fixture_tmp/$fixture_module.lean" > "$fixture_tmp/$fixture-compile.log" 2>&1; then
    cat "$fixture_tmp/$fixture-compile.log"
    exit 1
  fi
done

for fixture in "${negative_fixtures[@]}"; do
  if env LEAN_PATH="$fixture_tmp:$fixture_lean_path" "$fixture_audit" \
      --interface "InterfaceAudit${fixture}" > "$fixture_tmp/$fixture-audit.log" 2>&1; then
    printf 'interface audit test: wrongly accepted %s\n' "$fixture"
    exit 1
  fi
  # A missing module, compiler error, or failed type inference is not a passing negative test.
  if ! grep -Eq 'refers to .*(library module|Part III|outside the Mathlib import closure)' "$fixture_tmp/$fixture-audit.log"; then
    cat "$fixture_tmp/$fixture-audit.log"
    exit 1
  fi
  printf 'interface audit test: rejected %s\n' "$fixture"
done

# This helper is generated by Lean's proof abstraction, rather than handwritten by the fixture.
if ! grep -Fq 'generatedAux._proof_1 refers to' "$fixture_tmp/GeneratedAuxLeak-audit.log"; then
  cat "$fixture_tmp/GeneratedAuxLeak-audit.log"
  exit 1
fi

for fixture in "${positive_fixtures[@]}"; do
  if ! env LEAN_PATH="$fixture_tmp:$fixture_lean_path" "$fixture_audit" \
      --interface "InterfaceAudit${fixture}" > "$fixture_tmp/$fixture-audit.log" 2>&1; then
    cat "$fixture_tmp/$fixture-audit.log"
    exit 1
  fi
  printf 'interface audit test: accepted %s\n' "$fixture"
done
